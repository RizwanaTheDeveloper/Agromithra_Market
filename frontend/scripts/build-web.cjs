const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { createHash } = require('node:crypto');
const root = path.resolve(__dirname, '..');
const source = path.join(root, 'src');
const destination = path.join(root, 'public/market');
const manifest = JSON.parse(fs.readFileSync(path.join(source, 'manifest.json'), 'utf8'));
fs.mkdirSync(destination, { recursive: true });
const read = name => fs.readFileSync(path.join(source, name), 'utf8');
// The API URL is fixed at build time: --offline, MARKET_API_URL, EXPO_PUBLIC_API_URL, or frontend/.env.
// An empty value builds the self-contained offline demo.
function configuredApiUrl() {
  if (process.argv.includes('--offline')) return '';
  if (process.env.MARKET_API_URL !== undefined) return process.env.MARKET_API_URL.trim();
  if (process.env.EXPO_PUBLIC_API_URL !== undefined) return process.env.EXPO_PUBLIC_API_URL.trim();
  try {
    const line = fs.readFileSync(path.join(root, '.env'), 'utf8').split(/\r?\n/).find(l => /^\s*(MARKET_API_URL|EXPO_PUBLIC_API_URL)\s*=/.test(l));
    return line ? line.slice(line.indexOf('=') + 1).trim().replace(/^["']|["']$/g, '') : '';
  } catch { return ''; }
}
const apiUrl = configuredApiUrl();
if (apiUrl && !/^https?:\/\//i.test(apiUrl)) throw new Error('API URL must start with http:// or https://');
function configuredDataSource() {
  if (process.argv.includes('--offline')) return 'local';
  let value = process.env.MARKET_DATA_SOURCE;
  if (value === undefined) {
    try {
      const line = fs.readFileSync(path.join(root, '.env'), 'utf8').split(/\r?\n/).find(line => /^\s*MARKET_DATA_SOURCE\s*=/.test(line));
      if (line) value = line.slice(line.indexOf('=') + 1).trim().replace(/^["']|["']$/g, '');
    } catch (_) { /* A frontend .env is optional. */ }
  }
  value = value === undefined ? (apiUrl ? 'server' : 'local') : value.trim();
  if (!['local', 'server'].includes(value)) throw new Error('MARKET_DATA_SOURCE must be local or server');
  return value;
}
const dataSource = configuredDataSource();
if (dataSource === 'server' && !apiUrl) throw new Error('Set MARKET_API_URL when MARKET_DATA_SOURCE=server');
const config = `window.MARKET_CONFIG=${JSON.stringify({ apiUrl, dataSource })};`;
const bundle = [config, ...manifest.scripts.map(name => `\n/* ${name} */\n${name === 'data/marketplace.json' ? 'window.MARKET_DATA=' + JSON.stringify(JSON.parse(read(name))) + ';' : read(name)}`)].join('\n');
new vm.Script(bundle, { filename: 'market-app.js' });
fs.writeFileSync(path.join(destination, 'app.js'), bundle);
fs.writeFileSync(path.join(destination, 'app.css'), manifest.styles.map(read).join('\n'));
const version = createHash('sha256').update(bundle).update(manifest.styles.map(read).join('\n')).digest('hex').slice(0,16);
fs.writeFileSync(path.join(destination,'build.json'),JSON.stringify({version}));
fs.copyFileSync(path.join(source,'core/recovery-bridge.html'),path.join(destination,'recover.html'));
fs.mkdirSync(path.join(root,'src/generated'),{recursive:true});
const buildInfo='// Generated by scripts/build-web.cjs.\nexport const marketplaceBuild = '+JSON.stringify(version)+';\n';
const buildInfoPath=path.join(root,'src/generated/build-info.ts');
if (!fs.existsSync(buildInfoPath) || fs.readFileSync(buildInfoPath,'utf8')!==buildInfo) fs.writeFileSync(buildInfoPath,buildInfo);
fs.cpSync(path.join(root, 'assets/images/apk'), path.join(destination, 'art'), { recursive: true });
const html = `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><meta name="theme-color" content="#174e39"><meta name="description" content="Agromitra Market: a complete, responsive agriculture marketplace frontend with local buying, selling and trade workflows."><title>Agromitra Market</title><link rel="stylesheet" href="/market/app.css"></head><body><a class="skip-link" href="#main-content">Skip to content</a><div id="app"></div><div id="modal-root"></div><div id="toast" role="status" aria-live="polite"></div><noscript>Enable JavaScript to use Agromitra Market.</noscript><script src="/market/app.js" defer></script></body></html>`;
fs.writeFileSync(path.join(destination, 'index.html'), html);
// Native builds use exactly the same frontend, with all illustration assets inlined.
const illustrations = Object.fromEntries(fs.readdirSync(path.join(destination, 'art')).filter(name => name.endsWith('.svg')).map(name => [name.slice(0, -4), 'data:image/svg+xml;base64,' + fs.readFileSync(path.join(destination, 'art', name)).toString('base64')]));
const nativeBridge = `window.MARKET_ART=${JSON.stringify(illustrations)};window.ExportBridge={printPdf:function(){var copy=document.documentElement.cloneNode(true);copy.querySelectorAll('script').forEach(function(node){node.remove();});window.ReactNativeWebView.postMessage(JSON.stringify({type:'print',html:'<!doctype html>'+copy.outerHTML}));}};window.print=window.ExportBridge.printPdf;`;
const nativeHTML = html.replace('<html lang="en">', '<html lang="en" data-native="true">').replace('<link rel="stylesheet" href="/market/app.css">', () => '<style>' + manifest.styles.map(read).join('\n') + '</style>').replace('<script src="/market/app.js" defer></script>', () => '<script>' + (nativeBridge + bundle).replace(/<\/script/gi, '<\\/script') + '</script>');
fs.mkdirSync(path.join(root, 'src/generated'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/generated/market-html.ts'), '// Generated by scripts/build-web.cjs. Edit the related source folders under src instead.\nexport const marketplaceHTML = ' + JSON.stringify(nativeHTML) + ';\n');
if (process.argv.includes('--standalone')) {
  const dist = path.join(root, 'dist');
  fs.mkdirSync(dist, { recursive: true });
  fs.cpSync(destination, path.join(dist, 'market'), { recursive: true });
  fs.writeFileSync(path.join(dist, 'index.html'), html);
}
console.log(`Built complete marketplace: ${manifest.scripts.length} source modules, ${manifest.styles.length} stylesheets. ${dataSource === 'server' && apiUrl ? 'Connected to ' + apiUrl : 'Local frontend JSON data.'}`);
